namespace DesktopOrganizer.UI.Models;

/// <summary>
/// Display size for system icon panel items.
/// Numeric value is the icon dimension in pixels.
/// </summary>
public enum SystemIconSize
{
    /// <summary>Small icons (32 × 32 px).</summary>
    Small = 32,

    /// <summary>Medium icons (48 × 48 px). Default.</summary>
    Medium = 48,

    /// <summary>Large icons (64 × 64 px).</summary>
    Large = 64,
}
